// Run with: playwright-cli -s=moonheap run-code --filename scripts/browser-smoke.js
async (page) => {
  const check=(ok,message)=>{if(!ok)throw new Error(message);};
  const settle=async()=>{await page.locator('#busy').waitFor({state:'hidden',timeout:90000});check(await page.locator('#error').isHidden(),await page.locator('#error').textContent());};
  const tab=async view=>{await page.locator('[data-view="'+view+'"]').click();await settle();};
  const search=async value=>{await page.locator('#search').fill(value);await page.locator('#search-form').evaluate(form=>form.requestSubmit());await settle();};
  const detail=async view=>{await page.locator('[data-detail="'+view+'"]').click();await settle();};
  await page.setViewportSize({width:1440,height:1040});await page.reload();
  await page.locator('#demo-empty').click();await settle();
  check(await page.locator('#stat-nodes').textContent()==='42','demo node count');
  check((await page.locator('#slot2').textContent()).includes('residual.heapsnapshot'),'third snapshot loaded');
  check((await page.locator('#table-body').textContent()).includes('+512.0 KiB'),'growth delta');
  await page.locator('#identity').check();await settle();
  check((await page.locator('#identity-result').textContent()).includes('新增 32'),'identity count');
  await page.locator('#change-next').click();await settle();
  check(await page.locator('#changes-body tr').count()===11,'independent changes pagination');
  check(await page.locator('#next').isDisabled(),'group page independent of object changes');
  await page.locator('#change-prev').click();await settle();
  await page.locator('#change-status').selectOption('retention_changed');await settle();
  check(await page.locator('#changes-body tr').count()===3,'unchanged-size container retention change');
  await page.locator('#change-status').selectOption('');await settle();
  await tab('investigate');await page.locator('#kind').selectOption('object');await settle();await search('PhotoEntry');
  check(await page.locator('#changes-body tr').count()===2,'two new entries survive cleanup');
  check((await page.locator('#table-body').textContent()).includes('2 → 18 → 4'),'three stage group counts');
  await page.locator('#changes-body .row-link').first().click();await settle();
  check((await page.locator('#stat-active').textContent()).startsWith('C'),'survivor opens cleanup snapshot');
  await detail('path');check((await page.locator('#detail-content').textContent()).includes('photoCache'),'survivor holder path');
  await detail('paths');check(await page.locator('#detail-content .path-block').count()>0,'multiple paths UI');
  await detail('source');check((await page.locator('#detail-content').textContent()).includes('没有分配调用栈'),'missing source is explicit');
  await page.locator('#bookmark').click();
  await detail('incoming');await page.locator('#detail-content .row-link').first().click();await settle();
  await page.locator('#history-back').click();await settle();check(await page.locator('#detail-name').textContent()==='PhotoEntry','object back navigation');
  await page.locator('#history-forward').click();await settle();check(await page.locator('#detail-name').textContent()==='Array','object forward navigation');
  await page.locator('#save-workspace').click();await settle();await page.reload();
  await page.locator('#restore-workspace').click();await settle();
  check(await page.locator('#changes-body tr').count()===2,'saved investigation and filters restored');
  check(await page.locator('#bookmark-list .bookmark-row').count()===1,'saved bookmark restored');
  await page.locator('#bookmark-list .row-link').click();await settle();
  check(await page.locator('#detail-name').textContent()==='PhotoEntry','restored bookmark resolves');
  await page.locator('#clear-saved').click();await settle();
  console.log('PASS: three snapshots, retained growth, independent pagination, survivors, paths, source absence, history, workspace and bookmarks.');

  await search('');await page.locator('#kind').selectOption('');await settle();await tab('tree');
  check(await page.locator('#treemap rect').count()>0,'retained size map');
  await page.locator('#table-body .tree-action').first().click();await settle();
  check(await page.locator('#tree-breadcrumbs button').count()>1,'dominator tree drilldown');
  await tab('groups');await page.locator('#kind').selectOption('array');await settle();
  check(await page.locator('#table-body tr').count()===1,'group kind filter');
  await page.locator('#kind').selectOption('');await settle();
  await page.locator('.snapshot-name[data-slot="1"]').click();await settle();await tab('nodes');
  await page.locator('#export-format').selectOption('json');
  await page.evaluate(()=>{const create=URL.createObjectURL.bind(URL);URL.createObjectURL=blob=>{window.reportBlob=blob;return create(blob);};});
  let downloaded=page.waitForEvent('download');await page.locator('#export').click();await settle();
  let download=await downloaded;await download.saveAs('work/browser-report.json');
  check(download.suggestedFilename()==='moonheap-nodes-report.json','export filename');
  const exported=await page.evaluate(async()=>JSON.parse(await window.reportBlob.text()));
  check(exported.complete&&exported.data.items.length===42,'full report includes all 42 rows rather than current 25');
  await page.locator('#reachability').selectOption('unreachable');await settle();
  check((await page.locator('#result-count').textContent()).startsWith('0'),'reachability filter');
  await page.locator('#reachability').selectOption('all');await settle();

  await page.locator('#file0').setInputFiles('examples/shared.heapsnapshot');await settle();
  check(!await page.locator('#identity').isChecked(),'replacement invalidates identity assertion');
  await search('9007199254740993');
  check((await page.locator('#table-body').textContent()).includes('@9007199254740993'),'precise 64-bit ID');
  await search('shared');
  await page.locator('#table-body .row-link').first().click();await settle();await detail('paths');
  check(await page.locator('#detail-content .path-block').count()===2,'shared object has two root paths');
  const raw=await(await page.request.get(new URL('/examples/shared.heapsnapshot',page.url()).href)).text();
  await search('');
  const unsafeName='<img src=x onerror=alert(1)>';
  await page.locator('#file0').setInputFiles({name:'untrusted.heapsnapshot',mimeType:'application/json',buffer:Buffer.from(raw.replace('"A"',JSON.stringify(unsafeName)))});await settle();
  check((await page.locator('#table-body').textContent()).includes(unsafeName),'untrusted name displayed');
  check(await page.locator('#table-body img').count()===0,'untrusted name stays text');
  const cyclic={snapshot:{meta:{node_fields:['type','name','id','self_size','edge_count'],node_types:[['synthetic','object'],'string','number','number','number'],edge_fields:['type','name_or_index','to_node'],edge_types:[['property'],'string','node']},node_count:3,edge_count:3},
    nodes:[0,0,1,0,1,1,1,3,32,1,1,2,5,32,1],edges:[0,3,5,0,3,10,0,3,5],strings:['root','CycleA','CycleB','holds']};
  await page.locator('#file0').setInputFiles({name:'cycles.heapsnapshot',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(cyclic))});await settle();await tab('cycles');
  check(await page.locator('#table-body .row-link').count()===1,'one retaining cycle');
  await page.locator('#table-body .row-link').click();await settle();
  check(await page.locator('#table-body tr').count()===2,'cycle members');
  await page.locator('#back-cycles').click();await settle();
  console.log('PASS: tree navigation, size map, filters, complete export, precise IDs, multiple paths, escaping and cycle members.');

  await page.locator('#file0').setInputFiles(['work/tracked/before.heapsnapshot','work/tracked/growth.heapsnapshot','work/tracked/cleanup.heapsnapshot']);await settle();
  await tab('investigate');await page.locator('#identity').check();await settle();await page.locator('#kind').selectOption('object');await settle();await search('MoonHeapCapturedEntry');
  check(await page.locator('#changes-body tr').count()===1,'real capture has one surviving entry');
  await page.locator('#changes-body .row-link').click();await settle();await detail('source');
  const sourceText=await page.locator('#detail-content').textContent();
  check(sourceText.includes('cache-scenario.mjs')||sourceText.includes('没有分配调用栈'),'real allocation source or explicit missing-record explanation');
  await detail('path');check(await page.locator('#detail-content .edge-row').count()>0,'real retaining path');
  await page.locator('#file0').setInputFiles({name:'bad.heapsnapshot',mimeType:'application/json',buffer:Buffer.from('{}')});
  await page.locator('#error').waitFor({state:'visible'});check((await page.locator('#error').textContent()).includes('missing field'),'malformed input error');
  await page.locator('#file0').setInputFiles('work/real/growth.heapsnapshot');await page.locator('#cancel').click();
  await page.locator('#demo-empty').waitFor({state:'visible'});
  check(await page.locator('#stat-nodes').textContent()==='—','cancellation resets analysis');
  await page.locator('#demo-empty').click();await settle();await page.locator('#identity').check();await settle();await tab('investigate');
  await page.locator('#kind').selectOption('object');await settle();await search('PhotoEntry');
  await page.locator('#changes-body .row-link').first().click();await settle();await detail('path');
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile page overflows');
  await page.screenshot({path:'work/browser-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1040});await page.screenshot({path:'work/browser-desktop.png',fullPage:true});
  console.log('PASS: real allocation capture, survivor source and paths, malformed input, cancellation/recovery and responsive layout.');
}

